// 히라가나 → 가타카나
export const toKatakana = (s) => s.replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60));

// 퀴즈에 나올 글자 목록. script: 'hira' | 'kata' | 'mix', groups: ['basic', …]
// 각 글자: { key: 'h:か', kana: 'か', romaji: 'ka', ko: '카', script: 'hira', group: 'basic' }
export function kanaPool(script, groups) {
  const scripts = script === 'mix' ? ['hira', 'kata'] : [script];
  return KANA_GROUPS.filter((g) => groups.includes(g.id)).flatMap((g) =>
    g.rows.flatMap(([h, romaji, ko]) =>
      scripts.map((sc) => {
        const kana = sc === 'kata' ? toKatakana(h) : h;
        return { key: `${sc === 'kata' ? 'k' : 'h'}:${kana}`, kana, romaji, ko, script: sc, group: g.id };
      })
    )
  );
}

