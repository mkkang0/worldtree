const parse = (text, tag) =>
  text
    .trim()
    .split('\n')
    .map((line) => {
      const [word, reading, meaning] = line.split('|');
      return { word, reading, meaning, tag, kanji: word !== reading };
    });

export const VOCAB = [...parse(NOUNS, 'n'), ...parse(VERBS, 'v'), ...parse(ADJECTIVES, 'a'), ...parse(ADVERBS, 'adv')];
export const vocabByWord = Object.fromEntries(VOCAB.map((v) => [v.word, v]));
